#!/usr/bin/env python3
"""Write utils/noses.cfg: where each ship's shots leave its sprite.

Shots start at the ship's nose instead of its centre. Wesnoth places a
missile by a fraction of the way from the attacker's hex to the target's
(missile_offset), so for each ship sprite this measures how far the nose
reaches ahead of the centre, facing north and facing north-east, over the
distance to the next hex that way (72 px straight, about 65 px diagonally).

Usage:
    make_noses.py --out <add-on dir>
"""

import argparse
import glob
import math
import os

import numpy as np
from PIL import Image

# Screen angle of the north-east facing, as in make_art.py.
DIAG = math.atan2(54, 36)
STEP = {"n": 72.0, "ne": math.hypot(54, 36)}
# A pixel is part of the hull when it is at least this opaque (skips glow).
SOLID = 128


def nose(path, facing):
    """Pixels from the sprite's centre to its nose, along `facing`."""
    a = np.array(Image.open(path).convert("RGBA"))[..., 3]
    ys, xs = np.nonzero(a >= SOLID)
    dx = xs + 0.5 - a.shape[1] / 2
    dy = ys + 0.5 - a.shape[0] / 2
    angle = 0.0 if facing == "n" else DIAG
    return float((dx * math.sin(angle) - dy * math.cos(angle)).max())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="add-on directory")
    args = ap.parse_args()
    units = os.path.join(args.out, "images/units/sc")
    stems = sorted(os.path.basename(p)[:-6] for p in glob.glob(os.path.join(units, "*-n.png")))
    lines = [
        "#textdomain wesnoth-Star_Control_TC",
        "# Generated by tools/make_noses.py: where each ship's shots leave it, as",
        "# a fraction of the way to the target (missile_offset), facing straight",
        "# (n, s) and diagonally. Used by SC_SHOT_FACING_FRAMES.",
        "",
    ]
    for stem in stems:
        for facing, name in (("n", "SC_NOSE"), ("ne", "SC_NOSE_DIAG")):
            path = os.path.join(units, f"{stem}-{facing}.png")
            if not os.path.exists(path):
                break
            frac = min(0.7, nose(path, facing) / STEP[facing])
            lines.append(f"#define {name}_{stem}\n{frac:.2f}#enddef")
    with open(os.path.join(args.out, "utils/noses.cfg"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"ok: {len(stems)} ships")


if __name__ == "__main__":
    main()
